package captcha

import (
	"encoding/json"
	"image"
	"image/color"
)

const (
	pointWidth  = 320
	pointHeight = 200
	charCount   = 4
	circleR     = 28
	charScale   = 3
)

// Point 点击坐标（已在 gocaptcha.go 中定义，这里只保留本地生成逻辑）

// generatePoint 生成点选验证码
// 后端生成带汉字的图片，前端 PointSelectionCaptcha 组件处理点击交互
func generatePoint() (*CaptchaData, error) {
	// 1. 生成背景图
	bg := drawBeautifulBg(pointWidth, pointHeight)

	// 2. 随机选择 4 个汉字
	chars := pickRandomChars(charCount)

	// 3. 在背景上绘制文字
	points := make([]Point, charCount)
	for i, ch := range chars {
		var x, y int
		for attempts := 0; attempts < 50; attempts++ {
			x = randInt(50, pointWidth-50)
			y = randInt(50, pointHeight-50)
			if !overlaps(points, i, x, y, 60) {
				break
			}
		}
		points[i] = Point{X: x, Y: y}
		drawCircleMarker(bg, x, y)
		drawChineseChar(bg, ch, x, y)
	}

	// 4. 暗化背景
	darkenBackground(bg)

	// 5. 编码图片
	imgStr, err := toBase64(bg)
	if err != nil {
		return nil, err
	}

	// 6. 生成 ID 并保存答案
	captchaID, err := generateID()
	if err != nil {
		return nil, err
	}

	hintRunes := make([]string, charCount)
	for i, ch := range chars {
		hintRunes[i] = string(ch)
	}
	hintText := "请依次点击【" + joinChars(hintRunes, "，") + "】"

	answer, _ := json.Marshal(PointAnswer{Points: points, Chars: hintRunes})
	startTime, err := saveToRedis(captchaID, "point", string(answer))
	if err != nil {
		return nil, err
	}

	return &CaptchaData{
		CaptchaID: captchaID,
		Image:     imgStr,
		Type:      "point",
		HintText:  hintText,
		Chars:     hintRunes,
		StartTime: startTime,
	}, nil
}

// verifyPoint 验证点选答案，容差 ±15px
func verifyPoint(answerStr string, points []Point) (bool, string) {
	var answer PointAnswer
	decrypted, err := decryptAnswer(answerStr)
	if err != nil {
		return false, "验证码数据异常"
	}
	if err := json.Unmarshal([]byte(decrypted), &answer); err != nil {
		return false, "验证码数据异常"
	}
	if len(points) != len(answer.Points) {
		return false, "点击数量不正确"
	}
	for i, p := range points {
		if abs(p.X-answer.Points[i].X) > 15 || abs(p.Y-answer.Points[i].Y) > 15 {
			return false, "点击位置不正确"
		}
	}
	return true, "验证通过"
}

// overlaps 检查是否与已有点重叠
func overlaps(points []Point, count int, x, y, minDist int) bool {
	for i := 0; i < count; i++ {
		dx := points[i].X - x
		dy := points[i].Y - y
		if dx*dx+dy*dy < minDist*minDist {
			return true
		}
	}
	return false
}

// joinChars 连接字符数组
func joinChars(chars []string, sep string) string {
	result := ""
	for i, ch := range chars {
		if i > 0 {
			result += sep
		}
		result += ch
	}
	return result
}

// drawCircleMarker 绘制圆形标记
func drawCircleMarker(img *image.RGBA, cx, cy int) {
	// 外圈阴影
	for dy := -circleR - 3; dy <= circleR+3; dy++ {
		for dx := -circleR - 3; dx <= circleR+3; dx++ {
			dist := dx*dx + dy*dy
			if dist <= (circleR+3)*(circleR+3) && dist > circleR*circleR {
				px, py := cx+dx, cy+dy
				if px >= 0 && px < pointWidth && py >= 0 && py < pointHeight {
					orig := img.RGBAAt(px, py)
					img.Set(px, py, color.RGBA{
						R: uint8(float64(orig.R) * 0.6),
						G: uint8(float64(orig.G) * 0.6),
						B: uint8(float64(orig.B) * 0.6),
						A: orig.A,
					})
				}
			}
		}
	}
	// 白色边框
	for dy := -circleR; dy <= circleR; dy++ {
		for dx := -circleR; dx <= circleR; dx++ {
			dist := dx*dx + dy*dy
			if dist <= circleR*circleR && dist > (circleR-3)*(circleR-3) {
				px, py := cx+dx, cy+dy
				if px >= 0 && px < pointWidth && py >= 0 && py < pointHeight {
					img.Set(px, py, color.RGBA{R: 255, G: 255, B: 255, A: 220})
				}
			}
		}
	}
	// 内部半透明白色
	for dy := -(circleR - 3); dy <= circleR-3; dy++ {
		for dx := -(circleR - 3); dx <= circleR-3; dx++ {
			if dx*dx+dy*dy <= (circleR-3)*(circleR-3) {
				px, py := cx+dx, cy+dy
				if px >= 0 && px < pointWidth && py >= 0 && py < pointHeight {
					orig := img.RGBAAt(px, py)
					img.Set(px, py, color.RGBA{
						R: uint8(float64(orig.R)*0.5 + 127),
						G: uint8(float64(orig.G)*0.5 + 127),
						B: uint8(float64(orig.B)*0.5 + 127),
						A: orig.A,
					})
				}
			}
		}
	}
}

// drawChineseChar 在指定位置绘制汉字
func drawChineseChar(img *image.RGBA, ch rune, cx, cy int) {
	bitmap, ok := chineseBitmaps[ch]
	if !ok {
		return
	}
	textColor := color.RGBA{R: 30, G: 30, B: 100, A: 255}
	bitmapSize := 16
	offsetX := cx - (bitmapSize*charScale)/2
	offsetY := cy - (bitmapSize*charScale)/2
	for row := 0; row < bitmapSize; row++ {
		for col := 0; col < bitmapSize; col++ {
			if bitmap[row]&(1<<(15-uint(col))) != 0 {
				for dy := 0; dy < charScale; dy++ {
					for dx := 0; dx < charScale; dx++ {
						px := offsetX + col*charScale + dx
						py := offsetY + row*charScale + dy
						if px >= 0 && px < pointWidth && py >= 0 && py < pointHeight {
							img.Set(px, py, textColor)
						}
					}
				}
			}
		}
	}
}

// darkenBackground 暗化背景
func darkenBackground(img *image.RGBA) {
	for y := 0; y < pointHeight; y++ {
		for x := 0; x < pointWidth; x++ {
			orig := img.RGBAAt(x, y)
			img.Set(x, y, color.RGBA{
				R: uint8(int(orig.R) * 70 / 100),
				G: uint8(int(orig.G) * 70 / 100),
				B: uint8(int(orig.B) * 70 / 100),
				A: orig.A,
			})
		}
	}
}

// pickRandomChars 随机选择 n 个不重复的汉字
func pickRandomChars(n int) []rune {
	allChars := []rune("风限数据安系统管用服务发配置前后端口控质版本基管局报表单核审查财人事薪资考勤记文档知识库资产项目程工营销客户联系供应商采购库存物流配送生产制造质检验收合格率指标监控告警通知消息推送短邮站内信件模板工作流程审批")
	shuffled := make([]rune, len(allChars))
	copy(shuffled, allChars)
	for i := len(shuffled) - 1; i > 0; i-- {
		j := randInt(0, i+1)
		shuffled[i], shuffled[j] = shuffled[j], shuffled[i]
	}
	return shuffled[:n]
}

